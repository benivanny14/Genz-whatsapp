#!/usr/bin/env node
/**
 * prepare-render-env.js — tayarisha env za kuweka kwenye Render Dashboard.
 *
 * Inasoma backend/.env na kuandika `render-env-ready.env` (gitignored) yenye
 * sehemu ya kubandika (copy-paste) kwenye Render → Environment:
 *   - FIREBASE_* — thamani HALISI kutoka backend/.env (si siri zinachapishwa)
 *   - MANUAL_PAYMENT_RECEIVER_* — CHANGE_ME (wewe unajaza namba yako)
 *   - REDIS_URL — CHANGE_ME (kama unatumia Redis Cloud / Upstash)
 *   - RP_ID — domain ya Render (inafanya passkeys/WebAuthn kufanya kazi)
 *
 * Usage:
 *   node scripts/prepare-render-env.js
 *
 * Baada ya kujaza CHANGE_ME, fungua faili na ubandike yote kwenye Render
 * Dashboard → genz-whatsapp → Environment → Save.
 */
const fs = require('fs');
const path = require('path');

const BACKEND_ENV = path.join(__dirname, '..', 'backend', '.env');
const OUT = path.join(__dirname, '..', 'render-env-ready.env');

function readEnv(file) {
  const vals = {};
  if (!fs.existsSync(file)) return vals;
  for (const l of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    if (!l.trim() || l.trim().startsWith('#')) continue;
    const i = l.indexOf('=');
    if (i < 0) continue;
    vals[l.slice(0, i).trim()] = l.slice(i + 1).trim();
  }
  return vals;
}

