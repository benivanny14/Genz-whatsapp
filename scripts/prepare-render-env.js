const lines = [];
lines.push('# ── GENZ WhatsApp — env za Render Dashboard (generated by scripts/prepare-render-env.js) ──');
lines.push('# 🔴 BADILISHA CHANGE_ME kabla ya kubandika. FIREBASE_* ziko tayari (halisi).');
